import type { Brand } from './types'

function products(brandId: string, items: [string, string, string?][]) {
  return items.map(([name, description, code], i) => ({
    id: `${brandId}-${i + 1}`,
    name,
    description,
    code: code ?? `${brandId.slice(0, 3).toUpperCase()}-${String(i + 1).padStart(2, '0')}`,
  }))
}

